// PicoPods - keyboard input on top of any hal::KeyboardDevice.
//
// Two layers read the same event stream:
//
//   raw    poll_raw()   every press / release, for games (key state with down())
//   cooked poll()/wait() presses only, with modifiers attached and auto-repeat,
//                        for menus, editors and dialogs
//
// Reading the PicoCalc keyboard is slow (blocking I2C, ~16 ms per event). By
// default the device is read from the calling thread, at most every
// poll_interval_ms. start_background() moves the reads to core 1 and a
// lock-free queue, so the main loop never blocks (what PicoBoy does).
#pragma once
#include <atomic>
#include <cstdint>
#include <functional>

#include "pd/hal/keyboard.h"
#include "pd/keys.h"

namespace pd::input {

using hal::RawKey;

struct KeyEvent {
    uint8_t code = 0;
    bool ctrl = false, shift = false, alt = false;
    bool repeat = false;   // generated by auto-repeat
    // Printable byte to insert (Enter -> '\n'), or 0.
    char ch() const {
        if (ctrl || alt) return 0;
        if (code == key::Enter) return '\n';
        if (code >= 0x20 && code < 0x7F) return char(code);
        return 0;
    }
    bool is(uint8_t c) const { return code == c; }
    bool is_ctrl(char c) const { return ctrl && code == uint8_t(c); }   // is_ctrl('s')
};

struct Modifiers {
    bool ctrl = false, shift = false, alt = false;
};

class Keyboard {
public:
    struct Config {
        uint32_t repeat_delay_ms = 450;
        uint32_t repeat_rate_ms = 45;
    };

    Keyboard() = default;
    explicit Keyboard(hal::KeyboardDevice* dev) { attach(dev); }
    void attach(hal::KeyboardDevice* dev) { dev_ = dev; }
    void configure(const Config& c) { cfg_ = c; }
    hal::KeyboardDevice* device() const { return dev_; }

    // Polls the device on core 1 from now on. Only one Keyboard can do this.
    bool start_background();
    bool background() const { return bg_; }

    // ---- raw layer
    bool poll_raw(RawKey& ev);
    bool down(uint8_t code) const { return (state_[code >> 5] >> (code & 31)) & 1u; }
    Modifiers mods() const { return mods_; }

    // ---- cooked layer
    bool poll(KeyEvent& ev);
    KeyEvent wait();
    // Waits up to timeout_ms; false on timeout.
    bool wait_for(KeyEvent& ev, uint32_t timeout_ms);
    // Drops everything queued and stops auto-repeat.
    void flush();
    // Reads queued keys; true if Esc was among them. Use it inside long
    // operations; other keys are discarded.
    bool esc_pressed();
    // A callback for APIs that take a "keep going?" function (net, epub...):
    // returns false once Esc has been pressed.
    std::function<bool()> esc_checker();

    // Feeds an event as if it came from the device (tests, macros).
    void inject(const RawKey& ev);

private:
    bool next_raw(RawKey& ev);
    void track(const RawKey& ev);
    static void core1_loop();

    hal::KeyboardDevice* dev_ = nullptr;
    Config cfg_;
    uint32_t state_[8] = {};
    Modifiers mods_;
    bool shiftL_ = false, shiftR_ = false;
    uint8_t held_ = 0;
    uint32_t next_repeat_ = 0;
    uint32_t last_poll_ = 0;
    bool bg_ = false;

    static constexpr uint32_t kQueue = 64;   // power of two
    struct Ring {
        RawKey ev[kQueue];
        std::atomic<uint32_t> head{0}, tail{0};
        bool push(const RawKey& e);
        bool pop(RawKey& e);
    };
    Ring injected_;
    Ring bgq_;
};

}  // namespace pd::input
