#!/usr/bin/env python3
"""Convert Terminus PSF2 console fonts into the shared UI library's font file,
lib/interface/gfx/src/fonts_terminus.h (PicoPods pd::gfx).

Usage: python3 tools/gen_fonts.py [consolefonts_dir]
Needs the Uni2-Terminus*.psf.gz files (Debian/Ubuntu: console-setup-linux).
Terminus Font is licensed under the SIL Open Font License 1.1.
Covered code points: U+0020..U+007E and U+00A0..U+00FF (Latin-1).
"""
import gzip, struct, sys, os

SRC = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts"
FONTS = [("Uni2-Terminus12x6.psf.gz",  "t6x12"),
         ("Uni2-Terminus16.psf.gz",    "t8x16"),
         ("Uni2-Terminus20x10.psf.gz", "t10x20"),
         ("Uni2-Terminus24x12.psf.gz", "t12x24")]
CODEPOINTS = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100))


def load_psf1(data):
    mode, h = data[2], data[3]
    n = 512 if mode & 1 else 256
    glyphs = [data[4 + i * h: 4 + (i + 1) * h] for i in range(n)]
    cmap = {}
    if mode & 2:
        tab = data[4 + n * h:]
        idx, i = 0, 0
        while idx < n and i + 1 < len(tab):
            v = tab[i] | (tab[i + 1] << 8)
            i += 2
            if v == 0xFFFF:
                idx += 1
            elif v == 0xFFFE:  # skip combining sequences until 0xFFFF
                while i + 1 < len(tab) and (tab[i] | (tab[i + 1] << 8)) != 0xFFFF:
                    i += 2
            else:
                cmap.setdefault(v, idx)
    return 8, h, glyphs, cmap


def load_psf2(path):
    data = gzip.open(path).read()
    if data[0] == 0x36 and data[1] == 0x04:
        return load_psf1(data)
    magic, ver, hsz, flags, n, gsz, h, w = struct.unpack("<IIIIIIII", data[:32])
    assert magic == 0x864AB572, "not a PSF2 font"
    glyphs = [data[hsz + i * gsz: hsz + (i + 1) * gsz] for i in range(n)]
    cmap = {}
    if flags & 1:
        tab = data[hsz + n * gsz:]
        idx, i = 0, 0
        while idx < n and i < len(tab):
            j = tab.index(b"\xff", i)
            entry = tab[i:j]
            k = 0
            while k < len(entry):
                if entry[k] == 0xFE:  # start of combining sequences
                    break
                b = entry[k]
                ln = 1 if b < 0x80 else 2 if b < 0xE0 else 3 if b < 0xF0 else 4
                cmap.setdefault(ord(entry[k:k + ln].decode("utf-8")), idx)
                k += ln
            idx += 1
            i = j + 1
    return w, h, glyphs, cmap


out = ["// Terminus Font (c) Dimitar Toshkov Zhekov, SIL Open Font License 1.1",
       "// Glyph data from PicoCalc Writer, generated by tools/gen_fonts.py.",
       "// Included only by gfx.cpp.",
       "#pragma once", '#include "pd/gfx.h"', "", "namespace pd::gfx {",
       "// Generated by tools/gen_fonts.py - do not edit.",
       "// Terminus Font (c) Dimitar Toshkov Zhekov, SIL Open Font License 1.1", "",
       "// glyph index: cp 0x20..0x7E -> cp-0x20, cp 0xA0..0xFF -> cp-0xA0+95", ""]
names = []
for fname, name in FONTS:
    w, h, glyphs, cmap = load_psf2(os.path.join(SRC, fname))
    bpr = (w + 7) // 8
    out.append(f"static const uint8_t {name}_data[] = {{")
    for cp in CODEPOINTS:
        g = glyphs[cmap.get(cp, cmap[ord('?')])]
        out.append("  " + ",".join(f"0x{b:02x}" for b in g[:h * bpr]) + f", // U+{cp:04X}")
    out.append("};")
    out.append(f"static const Font {name} = {{{w}, {h}, {bpr}, {name}_data}};\n")
    names.append(name)
out.append("static const Font* const kFonts[] = {" + ", ".join("&" + n for n in names) + "};")
out.append(f"static constexpr int kFontCount = {len(names)};")
out += ["", "}  // namespace pd::gfx"]
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "gfx", "src",
                   "fonts_terminus.h")
open(dst, "w").write("\n".join(out) + "\n")
print("wrote", dst, names)
